# Рубрики книги → рубрики приложения.
def rubric_for(r: str) -> str:
    r = r.lower()
    if r.startswith("соус"):
        return "sauce"
    if r.startswith("суп"):
        return "soup"
    if any(w in r for w in ("салат", "закуск", "тапас", "мезе", "банчан", "ролл")):
        return "salad"
    if any(w in r for w in ("выпечк", "десерт", "хлеб", "пицца", "хачапури", "сладост")):
        return "pastry"
    return "main"


