    RUBRICS["sauce"] = ("Соусы", "drop", "jar")

    existing_titles = {r["title"].lower() for r in R}
    used_ids = {r["id"] for r in R}
    prefixes = {"russian": "ru", "italian": "it", "georgian": "ge", "vietnamese": "vn", "french": "fr", "mexican": "mx",
                "japanese": "jp", "spanish": "es", "indian": "in", "korean": "kr", "turkish": "tr", "uzbek": "uz"}
    added = 0
    for book in json.loads(DATA.read_text(encoding="utf-8")):
        if book["title"] in DUPLICATES or book["title"].lower() in existing_titles:
            continue
        cuisine = CUISINES[book["cuisine"]]
        rubric = rubric_for(book["rubric"])
        minutes, servings = time_and_servings(book["notes"])
        ingredients = []
        for name, amount in book["ingredients"]:
            for part, part_amount in split_composite(name, amount):
                cat = category_for(part)
                if not cat:  # None — соль, вода, «см. соусы»; False отсеян проверкой выше
                    continue
                parsed = parse_amount(part_amount)
                if parsed is None:
                    continue
                value, unit = parsed
                if value <= 0:
                    continue
                qty, u = to_ingredient(cat, value, unit, P[cat], NEW.get(cat))
                if qty <= 0:
                    continue
                ingredients.append((_title(part), cat, qty, u))
        if not ingredients or not book["steps"]:
            continue
        rid = f"{prefixes[cuisine]}-{slug(book['title'])}"
        while rid in used_ids:
            rid += "-2"
        used_ids.add(rid)
        summary = book["notes"][1] if len(book["notes"]) > 1 and not book["notes"][1].startswith("Время") else ""
        r = recipe_fn(rid, book["title"], summary, rubric, minutes, servings, ingredients, book["steps"])
        r["cuisine"] = cuisine
        r["icon"] = icon_for(book["title"], rubric)
        R.append(r)
        added += 1
    return added


