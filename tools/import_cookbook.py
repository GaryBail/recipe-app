def _all_have_piece(products: list) -> bool:
    return bool(products) and all(p[7].get("piece") for p in products)


def to_ingredient(cat: str, value: float, unit: str, products: list, meta: tuple | None) -> tuple[float, str]:
    """Количество в единицах приложения: g, ml или pcs."""
    kind = meta[0] if meta else ("ml" if cat in LIQUID else "g")
    tbsp = meta[1] if meta else TBSP.get(cat, 15)
    piece = (meta[2] if meta else None) or PIECE_FALLBACK.get(cat)
    pcs_ok = _all_have_piece(products)

    def grams_per_piece() -> float:
        if piece:
            return piece
        pieces = [p[7].get("piece") for p in products if p[7].get("piece")]
        return pieces[0] if pieces else 100

    if unit in ("g", "ml"):
        return round(value, 1), unit
    if unit in ("tbsp", "tsp", "cup"):
        spoons = value if unit == "tbsp" else value / 3 if unit == "tsp" else value / 15
        if kind == "ml":
            return round(spoons * 15, 1), "ml"
        return round(spoons * tbsp, 1), "g"
    if unit == "clove":
        return (value, "pcs") if cat == "garlic" else (round(value * 5, 1), "g")
    if unit == "head":
        if cat == "garlic":
            return value * 10, "pcs"
        return (value, "pcs") if pcs_ok else (round(value * (piece or 500), 1), "g")
    if unit == "bunch":
        return round(value * 30, 1), "g"
    if unit == "stalk":
        return (value, "pcs") if pcs_ok else (round(value * (piece or 40), 1), "g")
    if unit == "sprig":
        return round(value * 2, 1), "g"
    if unit == "leaf":
        return round(value * 0.5, 1), "g"
    if unit == "slice":
        return round(value * 20, 1), "g"
    # штуки
    if pcs_ok:
        return value, "pcs"
    return round(value * grams_per_piece(), 1), "g"


