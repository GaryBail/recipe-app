def _num(s: str) -> float:
    s = s.strip().replace(",", ".").replace("½", ".5").replace("¼", ".25").replace("¾", ".75")
    if "/" in s and re.fullmatch(r"\d+/\d+", s):
        a, b = s.split("/")
        return float(a) / float(b)
    if s.startswith("."):
        s = "0" + s
    return float(s)


NUM = r"(\d+(?:[.,]\d+)?|\d+/\d+|½|¼|¾)"
RANGE = rf"{NUM}(?:\s*[–-]\s*{NUM})?"


def parse_amount(text: str) -> tuple[float, str] | None:
    """«2 шт. (400 г)» → (400, "g"); «2 ст. л.» → (2, "tbsp"); «1,5 кг» → (1500, "g"); None — без количества."""
    t = text.lower().replace("\xa0", " ").strip()
    t = re.sub(r"^по\s+", "", t)
    # граммы в скобках точнее штук
    m = re.search(rf"\(\s*(?:~|около\s*)?{RANGE}\s*(г|кг|мл|л)\b", t)
    if m:
        return _value(m.group(1), m.group(2)) * {"г": 1, "кг": 1000, "мл": 1, "л": 1000}[m.group(3)], \
            ("ml" if m.group(3) in ("мл", "л") else "g")
    m = re.match(rf"\s*{RANGE}\s*(?:\+\s*\d+\s*)?([а-яa-z.\s]*)", t)
    if not m:
        if "щепот" in t:
            return 0.5, "g"
        if re.match(r"(большой )?пуч", t):
            return 1, "bunch"
        if "горст" in t:
            return 30, "g"
        if t.startswith("несколько лист"):
            return 3, "leaf"
        return None
    value = _value(m.group(1), m.group(2))
    unit = m.group(3).strip()
    table = [("кг", 1000, "g"), ("г", 1, "g"), ("мл", 1, "ml"), ("л", 1000, "ml"), ("ст. л", 1, "tbsp"), ("ст.л", 1, "tbsp"),
             ("ч. л", 1, "tsp"), ("ч.л", 1, "tsp"), ("стакан", 250, "cup"), ("зубч", 1, "clove"), ("пуч", 1, "bunch"),
             ("стеб", 1, "stalk"), ("головк", 1, "head"), ("веточ", 1, "sprig"), ("лист", 1, "leaf"), ("щепот", 0.5, "g"),
             ("стручк", 1, "pcs"), ("стручок", 1, "pcs"), ("шт", 1, "pcs"), ("банк", 400, "g"), ("ломтик", 1, "slice"),
             ("полоск", 1, "pcs"), ("коробоч", 1, "pcs"), ("порци", 1, "pcs"), ("филе", 1, "pcs"), ("кусоч", 1, "pcs")]
    for prefix, k, u in sorted(table, key=lambda x: -len(x[0])):  # «листов» и «ломтиков» — не литры
        if unit.startswith(prefix):
            if prefix == "г" and unit.startswith("голов"):
                continue
            return value * k, u
    if unit == "" or unit.startswith("("):
        return value, "pcs"
    return value, "pcs"


def _value(a: str, b: str | None) -> float:
    x = _num(a)
    return (x + _num(b)) / 2 if b else x


def split_composite(name: str, amount: str) -> list[tuple[str, str]]:
    """«Соль, сахар» + «1,5 ч. л. / 1 ч. л.» → две строки; «Кинза, базилик» + «по 1 пучку» → каждой."""
    parts = [p.strip() for p in re.split(r",\s*|\s\+\s", name) if p.strip()]
    amounts = [a.strip() for a in amount.split("/")]
    if len(parts) > 1 and len(amounts) == len(parts):
        return list(zip(parts, amounts))
    if len(parts) > 1 and amount.lower().startswith("по "):
        return [(p, amount) for p in parts]
    return [(name, amount)]


