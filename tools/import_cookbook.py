def time_and_servings(notes: list[str]) -> tuple[int, int]:
    minutes, servings = 0, 4
    for n in notes:
        if not n.startswith("Время"):
            continue
        h = re.search(r"(\d+(?:[.,]\d+)?)\s*ч\b", n)
        m = re.search(r"(\d+)\s*мин", n)
        d = re.search(r"(\d+)\s*(?:сут|дн)", n)
        minutes = int(float(h.group(1).replace(",", ".")) * 60 if h else 0) + (int(m.group(1)) if m else 0)
        if d:
            minutes += int(d.group(1)) * 24 * 60
        s = re.search(r"(\d+)(?:\s*[–-]\s*\d+)?\s*(?:порц|шт|штук|чашк|стакан|ролл|лепёш|бокал)", n)
        if s and "порц" in n[s.start():s.end() + 6]:
            servings = int(s.group(1))
    return minutes, servings


