def main():
    products = []
    for cat, items in P.items():
        for pid, name, brand, kcal, p, f, c, extra in items:
            products.append({
                "id": pid, "name": name, "brand": brand, "categoryId": cat, "barcode": None,
                "nutrition": {"kcal": kcal, "protein": p, "fat": f, "carbs": c},
                "gramsPerPiece": extra.get("piece"), "density": extra.get("density"),
            })

    categories = set(P)
    for r in R:
        for i in r["ingredients"]:
            assert i["categoryId"] in categories, f"{r['id']}: нет продуктов для {i['categoryId']}"
            if i["unit"] == "pcs":
                assert all(x[7].get("piece") for x in P[i["categoryId"]]), f"{i['categoryId']}: нет веса штуки"
        assert r["category"] in RUBRICS

    food_dir = Path(__file__).resolve().parents[1] / "RecipeApp" / "Resources" / "Food"
    for r in R:
        assert (food_dir / f"food-{r['icon']}.png").exists(), f"нет иллюстрации {r['icon']}"
    for v in RUBRICS.values():
        assert (food_dir / f"food-{v[2]}.png").exists(), f"нет иллюстрации {v[2]}"

    seed = {
        "version": SEED_VERSION,
        "rubrics": [{"id": k, "title": v[0], "symbol": v[1], "icon": v[2]} for k, v in RUBRICS.items()],
        "products": products,
        "recipes": R,
    }
    out = Path(__file__).resolve().parents[1] / "RecipeApp" / "Resources" / "seed.json"
    out.write_text(json.dumps(seed, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(R)} рецептов, {len(products)} продуктов, {len(categories)} категорий → {out}")


if __name__ == "__main__":
    main()
