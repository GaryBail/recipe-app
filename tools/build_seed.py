def ing(rid, n, title, cat, amount, unit):
    return {"id": f"{rid}-{n}", "title": title, "categoryId": cat, "amount": amount, "unit": unit}


def recipe(rid, title, summary, rubric, minutes, servings, ingredients, steps, featured=False, ids=None):
    items = []
    for n, (title_, cat, amount, unit) in enumerate(ingredients):
        iid = ids[n] if ids else f"{rid}-{n}"
        items.append({"id": iid, "title": title_, "categoryId": cat, "amount": amount, "unit": unit})
    return {"id": rid, "title": title, "summary": summary, "category": rubric, "cookMinutes": minutes,
            "servings": servings, "featured": featured, "ingredients": items, "steps": steps}


